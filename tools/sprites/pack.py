"""
Packs every PNG in assets/sprites/parts into 1024x1024 sprite sheets and writes:
  assets/sprites/SpriteSheet<N>.png                     <- upload these to Roblox
  src/ReplicatedStorage/Shared/Modules/SpriteRects.luau <- where each sprite sits

Adding art: drop a transparent PNG named after the sprite (e.g. PetCherryChick.png) into
assets/sprites/parts, run this script, then re-upload the sheets whose contents changed and
paste their new IDs into Shared/Modules/Assets.luau (SPRITE_SHEET_<N>).

Usage (from the repo root):  python3 tools/sprites/pack.py
Needs: pip install pillow
"""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
PARTS = ROOT / "assets/sprites/parts"
OUT_DIR = ROOT / "assets/sprites"
LUAU = ROOT / "src/ReplicatedStorage/Shared/Modules/SpriteRects.luau"
SHEET_SIZE = 1024  # Roblox keeps images up to 1024x1024 at full resolution
PAD = 6  # transparent gap between sprites so neighbours never bleed in


def target_size(name: str) -> int:
    """Largest dimension (px) a sprite is stored at. Big enough for UI, small enough to pack."""
    if name.endswith("Bar") or name.startswith("BarFrame"):
        return 600
    if name.startswith(("Pet", "Egg", "Truck")):
        return 300
    if name == "NotificationDot":
        return 96
    return 240


def main():
    items = []
    for path in sorted(PARTS.glob("*.png")):
        image = Image.open(path).convert("RGBA")
        scale = min(1.0, target_size(path.stem) / max(image.size))
        size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
        items.append((path.stem, image.resize(size, Image.LANCZOS)))

    # Simple shelf packing, tallest first.
    items.sort(key=lambda item: (-item[1].height, item[0]))
    sheets, rects = [], {}
    x = y = shelf = 0

    def new_sheet():
        sheets.append(Image.new("RGBA", (SHEET_SIZE, SHEET_SIZE), (0, 0, 0, 0)))
        return PAD, PAD, 0

    x, y, shelf = new_sheet()
    for name, image in items:
        w, h = image.size
        if x + w + PAD > SHEET_SIZE:
            x, y, shelf = PAD, y + shelf + PAD, 0
        if y + h + PAD > SHEET_SIZE:
            x, y, shelf = new_sheet()
        sheets[-1].alpha_composite(image, (x, y))
        rects[name] = (len(sheets), x, y, w, h)
        x += w + PAD
        shelf = max(shelf, h)

    for old in OUT_DIR.glob("SpriteSheet*.png"):
        old.unlink()
    for index, sheet in enumerate(sheets, 1):
        sheet.save(OUT_DIR / f"SpriteSheet{index}.png", optimize=True)

    lines = [
        "--!strict",
        "--[[",
        "\tSpriteRects (GENERATED by tools/sprites/pack.py - do not edit by hand)",
        "\tWhere each sprite sits on its sprite sheet: { sheet, x, y, width, height } in pixels.",
        "\tUse Shared/Modules/Sprites.luau to put a sprite on an ImageLabel.",
        "]]",
        "",
        f"-- Number of sheets: {len(sheets)} (Assets.SPRITE_SHEET_1 .. SPRITE_SHEET_{len(sheets)})",
        "return table.freeze({",
    ]
    for name in sorted(rects):
        sheet, rx, ry, rw, rh = rects[name]
        lines.append(f"\t{name} = table.freeze({{ {sheet}, {rx}, {ry}, {rw}, {rh} }}),")
    lines.append("})")
    LUAU.write_text("\n".join(lines) + "\n")

    print(f"{len(rects)} sprites on {len(sheets)} sheet(s)")
    for index in range(1, len(sheets) + 1):
        names = sorted(n for n, r in rects.items() if r[0] == index)
        print(f"  SpriteSheet{index}.png: {', '.join(names)}")


if __name__ == "__main__":
    main()
